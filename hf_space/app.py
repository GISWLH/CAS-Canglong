def heldout_figure(track: str, region: str, metric: str) -> go.Figure:
    col = "tcc" if metric.startswith("TCC") else "armse_K"
    d = HELDOUT[(HELDOUT.track == HELDOUT_TRACKS[track]) & (HELDOUT.region == HELDOUT_REGIONS[region])]
    fig = go.Figure()
    palette = {
        "CAS-Canglong 0.25°": (CAS_RED, 3.2, None),
        "ERA5 Persistence": ("#52514e", 2.0, "dash"),
        "ECMWF": ("#1baf7a", 2.2, "dash"),
        "CMA": ("#eb6834", 2.0, "dash"),
        "UKMO": ("#7c3aed", 1.8, "dash"),
        "BoM": ("#d97706", 1.8, "dash"),
        "CanSIPS-IC4": ("#0284c7", 1.6, "dot"),
        "COLA-RSMAS-CESM1": ("#9333ea", 1.6, "dot"),
        "GEM-NEMO": ("#059669", 1.6, "dot"),
        "NASA-GEOSS2S": ("#db2777", 1.6, "dot"),
    }
    models_sorted = sorted(
        d.groupby("model"),
        key=lambda kv: (kv[0] != "CAS-Canglong 0.25°", kv[0] != "ECMWF", kv[0] != "CMA", kv[0]),
    )
    for model, g in models_sorted:
        g = g.sort_values("lead")
        main = model == "CAS-Canglong 0.25°"
        color, width, dash = palette.get(model, ("#898781", 1.6, "dash"))
        fig.add_trace(go.Scatter(
            x=g.lead, y=g[col], mode="lines+markers", name=model,
            line=dict(color=color, width=width, dash=dash),
            marker=dict(size=8 if main else 5.5),
            hovertemplate=f"{model} · lead %{{x}}: %{{y:.4f}}<extra></extra>",
        ))
    fig.update_xaxes(title="Lead (months)", dtick=1)
    ytitle = "TCC / Index Correlation" if col == "tcc" else "ARMSE / RMSE (°C)"
    fig = _layout(fig, ytitle, 480)
    fig.update_layout(hovermode="closest", margin=dict(r=32, b=110), legend=dict(y=-0.22))
    return fig


def heldout_table(track: str, region: str) -> pd.DataFrame:
    d = HELDOUT[(HELDOUT.track == HELDOUT_TRACKS[track]) & (HELDOUT.region == HELDOUT_REGIONS[region])]
    t = d.groupby("model").agg(
        tcc=("tcc", "mean"), armse=("armse_K", "mean"), leads=("lead", "count"),
        months=("n_months", "first"), first=("first_valid", "min"), last=("last_valid", "max"),
    ).sort_values("tcc", ascending=False)
    return pd.DataFrame({
        "Model": t.index.tolist(),
        "Mean TCC": t.tcc.round(4).values,
        "Mean ARMSE (°C)": t.armse.round(4).values,
        "Leads": t.leads.values,
        "Samples": t.months.values,
        "Period": [f"{a} – {b}" for a, b in zip(t["first"], t["last"])],
    })


